#!/usr/bin/env python3
"""Generate docs/tools.md from the MCP server's own tool descriptions (run after changing a tool)."""
import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from proteus2py.server import mcp  # noqa: E402


async def main() -> str:
    tools = await mcp.list_tools()
    out = ["# MCP tool reference", "", "Generated by `tools/gen_tool_docs.py` from the tool descriptions the assistant sees.", ""]
    for t in sorted(tools, key=lambda t: t.name):
        out += [f"## `{t.name}`", "", (t.description or "").strip(), ""]
        props = (t.input_schema or {}).get("properties", {})
        if props:
            out += ["| parameter | type |", "|---|---|"]
            for k, v in props.items():
                typ = v.get("type") or "/".join(x.get("type", "?") for x in v.get("anyOf", [])) or "any"
                out.append(f"| `{k}` | {typ} |")
            out.append("")
    return "\n".join(out)

Path(__file__).resolve().parents[1].joinpath("docs/tools.md").write_text(asyncio.run(main()))
print("docs/tools.md written")
